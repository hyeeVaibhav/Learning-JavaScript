const month = 3;

switch(month){
  case 1:
    console.log("january");
    break;
  case 2:
    console.log("february");
    break;
  case 3:
    console.log("march");
    break;
  default:
    console.log("invalid month");
}
// note while running the code compiler will run till whole cases also after case 3 gets matched till last case but  default or break case will not get runned

