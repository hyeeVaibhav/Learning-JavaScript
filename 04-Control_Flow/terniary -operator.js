// ============================================================
// JAVASCRIPT - TERNARY OPERATOR
// ============================================================

// Ternary operator is a short-hand way of writing
// a simple if...else statement.
//
// Syntax:
//
// condition ? true : false
//
// condition → the condition to check
// true      → executes when condition is true
// false     → executes when condition is false


const teaPrice = 50;

teaPrice < 50
  ? console.log("tea is cheap")
  : console.log("tea is expensive");

// teaPrice = 50
// 50 < 50 → false
// Therefore, "tea is expensive" will be printed.


// ------------------------------------------------------------
// END NOTE
// ------------------------------------------------------------

// Ternary operator is useful for short and simple
// if...else conditions.
//
// Example:
//
// age >= 18 ? console.log("Adult") : console.log("Minor");
//
// Remember:
//
// condition ? true : false
//
// ============================================================