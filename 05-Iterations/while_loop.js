//while loop:

let index = 0;
while(index <= 20){
  console.log(`Value of index is ${index}`)
  index = index + 2
}


// while loop in array
let myArray = ['x','y','z']

let arr = 0;
while(arr < myArray.length){
  console.log(`Value is ${myArray[arr]}`)
  arr = arr+1
}

